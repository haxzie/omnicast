import AppKit
import Combine
import Foundation

/// Watches `NSPasteboard` and records every copy.
///
/// macOS has no change notification for the pasteboard, so polling the change
/// count is the supported approach; at 0.4 s it is invisible in Activity Monitor.
@MainActor
final class ClipboardMonitor: ObservableObject {
    @Published private(set) var latest: ClipboardEntry?

    private let store: ClipboardStore
    private let pasteboard = NSPasteboard.general
    private var changeCount: Int
    private var timer: Timer?
    private var pruneTimer: Timer?

    /// Password managers mark their pasteboard items as transient/concealed.
    /// Anything flagged that way never reaches disk.
    private static let concealedTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]

    init(store: ClipboardStore = .shared) {
        self.store = store
        self.changeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        pruneTimer = Timer.scheduledTimer(withTimeInterval: 3_600, repeats: true) { [weak self] _ in
            Task { @MainActor in
                guard let self else { return }
                let days = Settings.shared.clipboardRetentionDays
                let store = self.store
                Task.detached(priority: .background) { store.prune(retentionDays: days) }
            }
        }
        let days = Settings.shared.clipboardRetentionDays
        Task.detached(priority: .background) { [store] in store.prune(retentionDays: days) }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        pruneTimer?.invalidate()
        pruneTimer = nil
    }

    /// Writes text to the pasteboard without recording it again.
    func suppressNextChange() {
        changeCount = pasteboard.changeCount + 1
    }

    private func poll() {
        guard Settings.shared.clipboardHistoryEnabled else { return }
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount

        guard let item = pasteboard.pasteboardItems?.first else { return }
        if item.types.contains(where: { Self.concealedTypes.contains($0) }) { return }

        let app = NSWorkspace.shared.frontmostApplication
        let id = UUID().uuidString
        var entry: ClipboardEntry?

        if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let isURL = text.hasPrefix("http://") || text.hasPrefix("https://")
            entry = ClipboardEntry(
                id: id, content: isURL ? .url : .text, text: text, preview: Self.preview(of: text),
                sourceAppName: app?.localizedName, sourceBundleID: app?.bundleIdentifier,
                copiedAt: Date(), pinned: false, imagePath: nil)
        } else if let data = pasteboard.data(forType: .tiff) ?? pasteboard.data(forType: .png),
            let image = NSBitmapImageRep(data: data),
            let png = image.representation(using: .png, properties: [:])
        {
            let path = store.saveImage(png, id: id)
            entry = ClipboardEntry(
                id: id, content: .image, text: path ?? "",
                preview: "Image · \(image.pixelsWide)×\(image.pixelsHigh)",
                sourceAppName: app?.localizedName, sourceBundleID: app?.bundleIdentifier,
                copiedAt: Date(), pinned: false, imagePath: path)
        }

        guard let entry else { return }
        latest = entry
        let store = self.store
        Task.detached(priority: .utility) { store.insert(entry) }
    }

    private static func preview(of text: String) -> String {
        let collapsed = text
            .trimmingCharacters(in: .whitespacesAndNewlines)
            .replacingOccurrences(of: "\\s+", with: " ", options: .regularExpression)
        return collapsed.count > 160 ? String(collapsed.prefix(160)) + "…" : collapsed
    }
}
